def text_width(text: str, scale: int = 1) -> int:
    return max(0, (len(text) * 4 - 1) * scale)


def draw_text(draw: ImageDraw.ImageDraw, text: str, x: int, y: int, colour: str | tuple, scale: int = 1) -> None:
    for index, character in enumerate(text):
        for row, bits in enumerate(GLYPHS[character]):
            for column, bit in enumerate(bits):
                if bit == "1":
                    left = x + (index * 4 + column) * scale
                    top = y + row * scale
                    draw.rectangle((left, top, left + scale - 1, top + scale - 1), fill=colour)
